/**
 * F-601 PII 자동 마스킹 — **모델 전송 전**에 반드시 거친다.
 *
 * 대상: 성명 · 계좌번호 · 주민등록번호 · 연락처 (기획서 9.3).
 * 목표 미검출 0%이며, 합성 100건 테스트에서 **미검출 0건이 배포 조건**이다(N-501).
 *
 * 설계 방침 — **의심스러우면 가린다.** 과잉 마스킹은 판단 품질을 조금 떨어뜨리지만
 * 미검출은 개인정보 유출이다. 둘의 무게가 다르므로 재현율을 정밀도보다 우선한다
 * (EP-3 「실패는 안전한 방향으로」).
 *
 * 한국어 성명은 정규식만으로 완전히 잡을 수 없다. 그래서 두 겹으로 간다:
 *   1. 형태가 뚜렷한 것(주민번호·계좌·전화·이메일·카드)은 패턴으로 확실히 제거
 *   2. 성명은 **호칭·조사 문맥**에 기대어 잡고, 남은 위험은 EX-106 잔존 의심
 *      판정으로 넘긴다 — 확신이 없으면 전송을 차단한다
 */

export type MaskKind =
  | "RRN"        // 주민등록번호
  | "PHONE"      // 연락처
  | "ACCOUNT"    // 계좌번호
  | "CARD"       // 카드번호
  | "EMAIL"
  | "NAME"       // 성명
  | "ADDRESS";   // 주소(상세)

export type MaskResult = {
  /** 마스킹된 텍스트. 이 값만 모델로 나간다 */
  text: string;
  /** 무엇을 몇 개 가렸는지 — 실행 로그(F-402)와 마스킹 정확도 측정(N-501)에 쓴다 */
  counts: Record<MaskKind, number>;
  total: number;
  /**
   * 가리지 못한 PII가 남아 있을 수 있다는 의심. true면 **모델 전송을 차단한다**
   * (EX-106). 마스킹 실패를 조용히 통과시키지 않기 위한 안전장치다.
   */
  residualSuspicion: boolean;
  /** 의심 근거 — 사용자에게 무엇을 지워달라고 안내할지 정하는 데 쓴다 */
  suspicionReasons: string[];
};

const TOKEN: Record<MaskKind, string> = {
  RRN: "[주민등록번호]",
  PHONE: "[연락처]",
  ACCOUNT: "[계좌번호]",
  CARD: "[카드번호]",
  EMAIL: "[이메일]",
  NAME: "[이름]",
  ADDRESS: "[주소]",
};

/**
 * 순서가 중요하다. 주민번호를 먼저 지워야 그 숫자열이 계좌번호로 다시 잡히지 않는다.
 * 넓은 패턴(계좌·전화)은 좁은 패턴 뒤에 온다.
 */
const RULES: ReadonlyArray<{ kind: MaskKind; re: RegExp }> = [
  // 주민등록번호 — 하이픈 유무 모두. 뒷자리 첫 숫자는 성별코드 1~4·5~8(외국인)
  { kind: "RRN", re: /\b\d{6}\s*[-–—]\s*[1-8]\d{6}\b/g },
  { kind: "RRN", re: /\b\d{6}[1-8]\d{6}\b/g },

  { kind: "EMAIL", re: /\b[\w.+-]+@[\w-]+\.[\w.]{2,}\b/g },

  // 카드번호 — 4-4-4-4
  { kind: "CARD", re: /\b\d{4}\s*[-–—\s]\s*\d{4}\s*[-–—\s]\s*\d{4}\s*[-–—\s]\s*\d{4}\b/g },

  // 연락처 — 010-1234-5678 · 02-123-4567 · 국제표기
  // 금액 뒤에는 연락처가 오지 않는다. 「100000000원」이 연락처로 가려지던 것을 막는다
  { kind: "PHONE", re: /\b(?:\+?82[-\s]?)?0?1[0-9][-\s]?\d{3,4}[-\s]?\d{4}\b(?!\s*(?:원|만\s*원|억))/g },
  { kind: "PHONE", re: /\b0\d{1,2}[-\s]\d{3,4}[-\s]\d{4}\b/g },

  // 계좌번호 — 은행명이 앞에 붙거나, 하이픈으로 끊긴 10자리 이상 숫자열
  { kind: "ACCOUNT", re: /(?:계좌|통장|입금)\s*(?:번호)?\s*[:：]?\s*\d[\d-]{8,}\d/g },
  { kind: "ACCOUNT", re: /\b\d{2,6}-\d{2,6}-\d{2,8}(?:-\d{1,6})?\b/g },
  /**
   * 구분자 없는 9자리 이상 숫자열 — 계약번호·승인번호·접수번호가 흔하다.
   * 예전에는 잔존 의심으로 입력 전체를 막았다. 권유 문자에 흔한 번호 때문에
   * 검증을 시작도 못 하는 것보다 가리고 보내는 편이 맞다. 계좌번호일 수도 있으니
   * 계좌번호로 센다. 금액(…원·만원·억)은 판단에 필요한 조건이라 가리지 않는다.
   */
  { kind: "ACCOUNT", re: /\b\d{9,}\b(?!\s*(?:원|만\s*원|억))/g },

  // 주소 상세 — 「○○로 12길 34」 「○○아파트 101동 1002호」
  { kind: "ADDRESS", re: /[가-힣]+(?:시|도)\s*[가-힣]+(?:구|군|시)\s*[가-힣0-9]+(?:로|길|동)\s*[\d-]+/g },
  { kind: "ADDRESS", re: /\d+동\s*\d+호/g },
];

/**
 * 성명 패턴. 한국어 이름 단독으로는 일반 명사와 구분이 안 되므로
 * **호칭·역할어·라벨이 붙은 경우**를 축으로 잡는다.
 *
 * ⚠️ 호칭 뒤에 \b를 쓰면 안 된다 — JS의 단어 경계는 ASCII 기준이라
 * 「홍길동 씨가」·「이영희님께서」처럼 한글 조사가 이어지면 경계가 성립하지 않아
 * 전부 놓친다. 경계 대신 NOT_NAMES 예외 목록으로 오탐을 거른다.
 */

/** 이름 뒤에 붙을 수 있는 조사·서술 어미 */
const PARTICLES =
  "씨|님|께서|에게서|한테서|에게|한테|이가|이고|이라고|이며|이라|입니다|인데|은|는|이|가|을|를|의|와|과|께";

/**
 * 이름의 끝 조건. **이걸 요구하는 것이 과잉 마스킹을 막는 핵심이다.**
 *
 * 「이름을 확인했습니다」에서 「확인했습」이 이름으로 잡히지 않는 이유가 여기 있다 —
 * 조사를 붙여 봐도 「니다」 앞에서 어절이 끝나지 않아 매칭이 되물러난다.
 * 라벨이 이미 강한 단서인 규칙에서는 조사를 **선택**으로 둔다 (「신청인 홍길동 건으로」).
 */
const NAME_END = `(?=(?:${PARTICLES})?(?:\\s|$|[,.·/]))`;

/**
 * 조사를 **필수**로 요구하는 형태. 라벨이 약한 규칙에 쓴다.
 * 「제가 직접 작성하지」에서 「직접」이 이름으로 잡히던 것을 이걸로 막았다.
 */
const NAME_END_STRICT = `(?=(?:${PARTICLES})(?:\\s|$|[,.·/]))`;

/** 이름 앞에 오는 라벨. 조사가 끼어도 잡아야 한다 — 실측 미검출의 주된 원인이었다 */
const NAME_LABEL = "(?:성명|성함|존함|이름|신청인|피신청인|가입자|계약자|피보험자|수익자)";

/**
 * 한국 성씨. **라벨도 호칭도 없는 맨이름**(「홍길동이가 대신 가입했다」)을 잡는
 * 유일한 단서다. 인구 상위 성씨 위주로 두되, 오탐은 NOT_NAMES로 거른다.
 */
const SURNAMES =
  "김이박최정강조윤장임한오서신권황안송류전홍고문양손배백허유남심노하곽성차주우구나민진지엄채원천방공현함변염여추도소석선설마길연위표명기반왕금옥육인맹제탁국어편용봉";

const NAME_RULES: ReadonlyArray<RegExp> = [
  // 호칭이 붙은 경우
  /([가-힣]{2,4})(?=\s*(?:씨|님|군|양))/g,
  // 역할어가 붙은 경우. **성씨로 시작할 것을 요구한다** — 앞 어절이 용언이어도
  // 잡히기 때문이다(「작성하지 않았고 설계사가」에서 「않았고」가 이름이 됐다)
  new RegExp(
    `(?<=^|\\s|[,:：])([${SURNAMES}][가-힣]{1,3})(?=\\s*(?:설계사|모집인|상담원|담당자|과장|대리|팀장|부장|지점장))`,
    "g",
  ),
  // 고객·회원 호칭 앞의 이름 — 「홍길동 고객님」. 아래 잔존 의심 규칙이 「고객님」 같은
  // 일반 호칭을 더는 막지 않으므로, 그 앞에 붙은 이름은 여기서 가린다.
  new RegExp(
    `(?<=^|\\s|[,:：\\]\\)])([${SURNAMES}][가-힣]{1,3})(?=\\s*(?:고객|회원|가입자|이용자|신청자|대상자)\\s*님)`,
    "g",
  ),
  // 라벨 + (조사) + 이름 — 「이름은 홍길동이고」·「성함이 김철수인데」
  new RegExp(`${NAME_LABEL}\\s*(?:은|는|이|가|을|를|께서)?\\s*[:：]?\\s*([가-힣]{2,4})${NAME_END}`, "g"),
  // 자기 소개 — 「저는 홍길동이라고 합니다」
  new RegExp(`(?:저는|제가|본인은|본인이)\\s*([가-힣]{2,4})${NAME_END_STRICT}`, "g"),
  /**
   * 라벨·호칭 없는 맨이름 — 성씨로만 판별한다. **조건을 세 겹으로 조인다.**
   *
   * 한국어는 어절 안에 공백이 없어서 느슨하게 잡으면 참사가 난다. 실측:
   * 종**신보험**·해**지환급금**·**설명**을 이 전부 이름으로 잡혔다.
   *   ① `(?<=^|\s)` 어절 **시작**에서만  ② 성씨 + 정확히 2음절(=3음절 이름)
   *   ③ 조사 하나가 **반드시** 붙고 어절이 끝날 때만
   * 「해지환급금이」는 ③에서 떨어진다. ③의 조사를 **선택**으로 두면 「전화로」·
   * 「원금이」가 통째로 이름이 되므로(3음절 + 어절 경계) 반드시 필수여야 한다 —
   * 실측으로 확인했다.
   */
  new RegExp(
    `(?<=^|\\s)([${SURNAMES}][가-힣]{2})` +
      NAME_END_STRICT,
    "g",
  ),
];

/**
 * 호칭이 붙지만 이름이 아닌 말. 「선생님」의 「선생」, 「아저씨」의 「아저」가
 * 이름으로 잡히는 것을 막는다. 완전하지 않지만, 남는 오탐은 과잉 마스킹이라
 * 미검출보다 안전한 방향이다 (EP-3).
 */
const NOT_NAMES = new Set([
  // 호칭이 붙지만 이름이 아닌 말 — 「선생님」의 「선생」, 「아저씨」의 「아저」
  "아저", "아가", "선생", "어르", "고객", "회원", "사장", "손", "여러",
  "환자", "직원", "기사", "간호", "의사", "변호", "대표", "관계",
  // 역할어 — 「홍길동 과장님이」에서 호칭 규칙이 「과장」을 먼저 이름으로 먹으면
  // 정작 앞의 진짜 이름을 놓친다. 여기 넣어야 역할어 규칙이 「홍길동」을 잡는다
  "과장", "대리", "팀장", "부장", "차장", "실장", "지점", "지점장", "센터",
  // 가족 호칭 — **지우면 사실관계가 사라진다.** 「어머니가 가입하셨다」는
  // 대리 가입 여부 판단에 직결되는 정보다 (과잉 마스킹이 늘 안전하지는 않다)
  "어머니", "아버지", "할머니", "할아버지", "배우자", "보호자", "며느리", "따님",
  "아드님", "형제분", "자녀분", "부모님", "장모님", "시어머",
  // 흔한 3음절 명사
  "연락처", "가입일", "약관집", "명세서", "영수증", "상담원", "판매인",
  // 성씨로 시작하는 3음절 명사 — 맨이름 규칙의 오탐을 막는다.
  // 완전할 수 없지만, 남는 오탐은 과잉 마스킹이라 미검출보다 안전하다 (EP-3)
  "설명서", "신청서", "안내문", "계약서", "확인서", "진단서", "청약서", "증권사",
  "약관상", "보험사", "신청인", "가입자", "계약자", "고객님", "담당자", "상담원",
  "해지금", "환급금", "지급액", "보장액", "설계사", "모집인", "판매자", "금융사",
  "임직원", "관리자", "금감원", "소비자", "이용자", "신용도", "안내장", "통지서",
  // 권유 문자에 흔한 일반 호칭·관형어 — 「기존 고객님」·「우리 회원님」의 앞말은 이름이 아니다
  "대상자", "신청자", "사업자", "조합원", "원장", "우리", "기존", "신규", "모든", "해당",
  "전체", "우수", "주요", "개인", "기업", "법인", "소중한",
]);

/** 마스킹 후에도 남아 있을 수 있는 위험 신호 — EX-106 판정 근거 */
const SUSPICION: ReadonlyArray<{ re: RegExp; why: string; allow?: (match: RegExpExecArray) => boolean }> = [
  { re: /\b\d{9,}\b(?!\s*(?:원|만\s*원|억))/g, why: "9자리 이상 숫자열이 남아 있다" },
  // 여기도 \b를 쓰지 않는다 (위 NAME_RULES 주석과 같은 이유).
  // 「고객님 안녕하세요」·「회원님!」처럼 이름이 아닌 일반 호칭은 막지 않는다. 권유 문자
  // 대부분이 이렇게 시작해 검증을 시작도 못 했다 (2026-09-11 점검). 그 앞의 이름은
  // 위 NAME_RULES 가 먼저 가리고, 가려지지 않은 이름 형태는 그대로 막는다.
  { re: /([가-힣]{2,4})\s*(?:씨|님)(?![가-힣])/g, why: "호칭이 붙은 이름 형태가 남아 있다",
    allow: (match) => NOT_NAMES.has(match[1]) },
  { re: /\b\d{6}\s*[-–—]/g, why: "주민등록번호 앞자리 형태가 남아 있다" },
  /**
   * 하이픈 없는 앞자리 — **레드팀(A5)이 찾은 구멍이다** (2026.08.31).
   * 「앞자리가 800101인 주민번호예요」는 가려지지도(뒷자리가 없어 RRN 규칙 밖)
   * 막히지도(하이픈이 없어 위 규칙 밖) 않고 그대로 모델로 갔다.
   *
   * 6자리 숫자 자체를 의심하면 안 된다 — 이 도메인에서 10만~99만 원 금액이
   * 흔하다(「보험료 350000원」). 그래서 **맥락 낱말이 가까이 있을 때만** 잡는다.
   * 숫자가 낱말 앞뒤 어느 쪽에 오든 걸리게 두 방향을 본다.
   */
  {
    re: /(?:주민\s*(?:등록)?\s*번호|생년월일|앞\s*자리)[^\n]{0,12}\b\d{6}\b|\b\d{6}\b[^\n]{0,12}(?:주민\s*(?:등록)?\s*번호|생년월일|앞\s*자리)/g,
    why: "주민등록번호 앞자리·생년월일로 보이는 숫자가 남아 있다",
  },
];

export function maskPii(input: string): MaskResult {
  let text = input;
  const counts: Record<MaskKind, number> = {
    RRN: 0, PHONE: 0, ACCOUNT: 0, CARD: 0, EMAIL: 0, NAME: 0, ADDRESS: 0,
  };

  for (const { kind, re } of RULES) {
    text = text.replace(new RegExp(re.source, re.flags), () => {
      counts[kind] += 1;
      return TOKEN[kind];
    });
  }

  for (const [index,re] of NAME_RULES.entries()) {
    text = text.replace(new RegExp(re.source, re.flags), (m, captured: string, offset: number, source: string) => {
      if (NOT_NAMES.has(captured)) return m;
      // 목적·수단 표현 뒤의 역할어는 이름 단서가 아니다. 명시한 성명 라벨은 아래 규칙이 가린다.
      if (index === 1 && captured === "위해"
        && /[을를]\s+$/.test(source.slice(0,offset))) return m;
      // 성씨만으로 추측하는 마지막 규칙에서만 일반 금융 명사·서술어를 제외한다.
      // 성명 라벨·호칭·직책으로 명시한 이름에는 이 예외를 적용하지 않는다.
      if (index === NAME_RULES.length - 1 && (captured === "권유문"
        || /^(?:안내|신청|입금|송금|확인|설명|동의|설치|보장|적용|요구|제공)하$/u.test(captured))) return m;
      counts.NAME += 1;
      // 「성명: 홍길동」처럼 라벨이 함께 잡힌 규칙은 라벨을 남기고 값만 가린다
      return m.replace(captured, TOKEN.NAME);
    });
  }

  const reasons: string[] = [];
  for (const { re, why, allow } of SUSPICION) {
    const matches = [...text.matchAll(new RegExp(re.source, re.flags))];
    if (matches.some((match) => !allow?.(match))) reasons.push(why);
  }

  const total = Object.values(counts).reduce((a, b) => a + b, 0);
  return {
    text,
    counts,
    total,
    residualSuspicion: reasons.length > 0,
    suspicionReasons: reasons,
  };
}

/**
 * 모델 전송 게이트 (EX-106).
 * 잔존 의심이 있으면 전송하지 않고, 무엇을 지워야 하는지 사용자에게 돌려준다.
 * "마스킹했으니 괜찮겠지"로 넘기는 경로를 만들지 않는다.
 */
export function gateForModel(
  input: string,
): { ok: true; masked: MaskResult } | { ok: false; masked: MaskResult; ask: string } {
  const masked = maskPii(input);
  if (!masked.residualSuspicion) return { ok: true, masked };
  return {
    ok: false,
    masked,
    ask:
      "입력하신 내용에 개인정보로 보이는 부분이 남아 있어 그대로 전달하지 않았습니다. " +
      "이름·연락처·계좌번호·주민등록번호를 지우고 다시 입력해 주세요. " +
      "판단에는 그런 정보가 필요하지 않습니다.",
  };
}

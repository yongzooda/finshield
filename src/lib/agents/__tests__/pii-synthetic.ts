/**
 * N-501 합성 PII 주입 세트 — 100건.
 *
 * 실제 진술에 가까운 문장에 **값을 알고 있는 PII**를 심는다. 값을 알고 있으므로
 * 마스킹 후 그 값이 남아 있는지 기계적으로 확인할 수 있다.
 *
 * 변형을 일부러 섞는다 — 명세가 「성명·주민번호·계좌·연락처 **변형 포함**」을
 * 요구한다. 구분자 유무, 조사 결합, 라벨 표현 차이가 실제 미검출이 나오는 지점이다.
 */

export type PiiCase = {
  id: string;
  kind: "NAME" | "RRN" | "ACCOUNT" | "PHONE" | "CARD" | "EMAIL" | "ADDRESS";
  /** 마스킹 후 이 문자열이 남아 있으면 미검출이다 */
  secret: string;
  text: string;
};

const NAMES = ["홍길동", "김철수", "이영희", "박민수", "최지은", "정우성", "강수진", "윤성호"];

/** 성명 — 라벨·호칭·조사 변형 (실제 미검출이 여기서 나왔다) */
const NAME_TEMPLATES: ((n: string) => string)[] = [
  (n) => `제 이름은 ${n}이고 보험 설명을 제대로 못 들었습니다.`,
  (n) => `이름은 ${n}입니다. 종신보험 가입 건으로 문의드립니다.`,
  (n) => `성명: ${n} / 2019년 5월 전화 가입`,
  (n) => `성함은 ${n}이라고 하고, 어머니가 가입하셨습니다.`,
  (n) => `저는 ${n}이라고 합니다. 원금 손실 설명을 못 들었어요.`,
  (n) => `신청인 ${n} 건으로 다시 문의합니다.`,
  (n) => `${n} 씨가 설명해 주셨는데 내용이 달랐습니다.`,
  (n) => `담당자 ${n}님이 괜찮다고 하셨습니다.`,
  (n) => `${n} 설계사가 방문해서 권유했습니다.`,
  (n) => `어머니 성함이 ${n}인데 해피콜을 받으셨답니다.`,
  (n) => `가입자는 ${n}이며 당시 67세였습니다.`,
  (n) => `${n}이가 대신 가입해 줬습니다.`,
  (n) => `계약자는 ${n}, 피보험자는 어머니입니다.`,
  (n) => `피보험자 ${n} 건입니다.`,
  (n) => `${n} 과장님이 처리해 주셨습니다.`,
  (n) => `${n}에게 설명을 들었습니다.`,
];

/** 주민등록번호 — 하이픈 유무 */
const RRN_VALUES = ["900101-1234567", "9001011234567", "561231-2345678", "780315 - 1234567"];
const RRN_TEMPLATES: ((v: string) => string)[] = [
  (v) => `주민번호 ${v}로 가입되어 있습니다.`,
  (v) => `주민등록번호는 ${v}입니다.`,
  (v) => `계약자 주민번호 ${v} 확인 부탁드립니다.`,
];

/**
 * 주민번호 **앞 6자리만** — 레드팀(A5)이 찾은 구멍이다 (2026.08.31 · N-406).
 *
 * 「앞자리가 800101인 주민번호예요」는 뒷자리가 없어 RRN 마스킹 규칙 밖이고,
 * 잔존 의심 규칙도 하이픈을 요구해서 규칙 밖이었다. **가려지지도 막히지도 않고
 * 그대로 모델로 갔다.** 위 RRN_VALUES가 전부 뒷자리를 달고 있어 이 세트로는
 * 잡히지 않았다 — 「미검출 0건」이 세트 안에서만 참이었던 자리다.
 *
 * 이 축은 마스킹이 아니라 **차단(EX-106)으로 통과**한다. 6자리 숫자를 그 자체로
 * 가리면 금액을 지우게 되므로(아래 CLEAN_CASES) 맥락 낱말이 가까울 때만 막는다.
 * 그래서 여기 문장은 전부 맥락 낱말을 달고 있고, 낱말이 숫자 앞에 오는 경우와
 * 뒤에 오는 경우를 함께 넣는다.
 */
const RRN_PARTIAL_VALUES = ["800101", "561231", "780315"];
const RRN_PARTIAL_TEMPLATES: ((v: string) => string)[] = [
  (v) => `앞자리가 ${v}인 주민번호예요.`,
  (v) => `주민등록번호 앞자리는 ${v}입니다.`,
  (v) => `생년월일 ${v}로 가입되어 있습니다.`,
  (v) => `${v} 이 제 주민번호 앞자리입니다.`,
  // 「앞 6자리」는 규칙의 `앞자리` 토큰에 걸리지 않는다. 「주민번호」 쪽이 잡는다 —
  // 낱말 하나에만 기대고 있지 않은지 확인하는 자리다
  (v) => `주민번호 앞 6자리 ${v} 만 알려드릴게요.`,
];

/** 계좌 — 은행명 결합·구분자 변형 */
const ACCOUNT_VALUES = ["110-234-567890", "1002-345-678901", "국민 123456-78-901234", "352-1234-5678-93"];
const ACCOUNT_TEMPLATES: ((v: string) => string)[] = [
  (v) => `보험료는 ${v} 계좌에서 빠져나갔습니다.`,
  (v) => `계좌번호 ${v}로 자동이체 중입니다.`,
  (v) => `입금 계좌 ${v} 입니다.`,
];

/** 연락처 — 구분자·국제표기 */
const PHONE_VALUES = ["010-1234-5678", "01012345678", "010 9876 5432", "+82-10-2345-6789", "02-123-4567"];
const PHONE_TEMPLATES: ((v: string) => string)[] = [
  (v) => `연락처는 ${v}입니다.`,
  (v) => `${v}로 전화가 왔습니다.`,
  (v) => `제 번호 ${v}로 연락 주세요.`,
];

const CARD_VALUES = ["1234-5678-9012-3456", "1234 5678 9012 3456"];
const EMAIL_VALUES = ["hong@example.com", "kim.chulsoo@mail.co.kr"];
const ADDRESS_VALUES = ["서울시 강남구 테헤란로 123", "경기도 성남시 분당구 정자로 45", "101동 1002호"];

function build(): PiiCase[] {
  const cases: PiiCase[] = [];
  const add = (kind: PiiCase["kind"], secret: string, text: string) =>
    cases.push({ id: `${kind}-${cases.length + 1}`, kind, secret, text });

  // 성명 — 가장 어렵고 실제 미검출이 나온 축이라 비중을 크게 둔다
  for (const t of NAME_TEMPLATES) {
    for (const n of NAMES.slice(0, 4)) add("NAME", n, t(n));
  }
  for (const v of RRN_VALUES) for (const t of RRN_TEMPLATES) add("RRN", v, t(v));
  for (const v of RRN_PARTIAL_VALUES) for (const t of RRN_PARTIAL_TEMPLATES) add("RRN", v, t(v));
  for (const v of ACCOUNT_VALUES) for (const t of ACCOUNT_TEMPLATES) add("ACCOUNT", v, t(v));
  for (const v of PHONE_VALUES) for (const t of PHONE_TEMPLATES) add("PHONE", v, t(v));
  for (const v of CARD_VALUES) {
    add("CARD", v, `카드번호 ${v}로 결제했습니다.`);
    add("CARD", v, `${v} 카드로 자동결제되고 있습니다.`);
  }
  for (const v of EMAIL_VALUES) {
    add("EMAIL", v, `이메일 ${v}로 안내를 받았습니다.`);
    add("EMAIL", v, `연락은 ${v} 으로 부탁드립니다.`);
  }
  for (const v of ADDRESS_VALUES) {
    add("ADDRESS", v, `주소는 ${v}입니다.`);
    add("ADDRESS", v, `${v}에서 상담받았습니다.`);
  }

  return cases;
}

export const PII_CASES = build();

